// Layout, shell navigation and widget open/close.
const { test, expect } = require('@playwright/test')
const { openApp, send } = require('./support/mock')

test.describe('layout', () => {
  test('widget shows header, hero, input and disclaimer, without a welcome bubble', async ({ page }) => {
    await openApp(page)
    const w = page.locator('.xo-widget')
    await expect(w.locator('.xo-brand-text strong')).toHaveText('XO')
    await expect(w.locator('.xo-brand-text small')).toHaveText('Property & mortgage assistant')
    await expect(w.locator('.lang-switch-btn')).toHaveAttribute('aria-label', /English/)
    await expect(w.locator('.advisor-btn')).toBeVisible()
    for (const sel of ['.theme-toggle-btn', '.clear-chat-btn', '.close-widget-btn']) await expect(w.locator(sel)).toBeVisible()
    await expect(w.locator('.xo-hero h3')).toHaveText('How can I help with your property plans today?')
    await expect(w.locator('.message-wrapper')).toHaveCount(0)
    await expect(page.locator('#chat-text-input')).toHaveAttribute('placeholder', 'Ask about properties, mortgages, fees…')
    await expect(page.locator('.send-btn')).toBeDisabled()
    await expect(w.locator('.input-disclaimer')).toHaveText('Please verify important details independently.')
    await expect(w.locator('.feed-backdrop svg')).toHaveCount(1)
  })

  test('closing hides the widget, the launcher reopens it with the conversation intact', async ({ page, isMobile }) => {
    test.skip(isMobile, 'desktop shell behaviour')
    await openApp(page)
    await send(page, 'hello')
    await page.locator('.close-widget-btn').click()
    await expect(page.locator('.xo-widget')).toBeHidden()
    await expect(page.locator('.floating-launcher-btn')).toBeVisible()
    await page.locator('.floating-launcher-btn').click()
    await expect(page.locator('.xo-widget')).toBeVisible()
    await expect(page.locator('.message-wrapper.user')).toHaveCount(1)
    await page.locator('.close-widget-btn').click()
    await page.locator('.btn-luxury-purple').click()
    await expect(page.locator('.xo-widget')).toBeVisible()
  })

  test('header shows the chat only, with an Admin link to the admin module', async ({ page }) => {
    await openApp(page)
    await send(page, 'hello')
    await expect(page.locator('.app-header [role="tab"]')).toHaveCount(0)
    await expect(page.locator('.admin-view-container')).toHaveCount(0)
    const admin = page.locator('.app-header').getByRole('link', { name: 'Admin' })
    await expect(admin).toBeVisible()
    await expect(admin).toHaveAttribute('href', '/admin')
    await expect(page.locator('.xo-widget')).toBeVisible()
    await expect(page.locator('.app-footer')).toContainText('estimates, not offers')
  })
})
